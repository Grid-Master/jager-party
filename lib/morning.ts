export function chisinauDay(date = new Date()) {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: "Europe/Chisinau",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(date);
}

export function chisinauHour(date = new Date()) {
  const hour = new Intl.DateTimeFormat("en-GB", {
    timeZone: "Europe/Chisinau",
    hour: "2-digit",
    hourCycle: "h23",
  }).format(date);

  return Number(hour);
}

export function morningCaption(date = new Date()) {
  const [year, month, day] = chisinauDay(date).split("-").map(Number);
  const index =
    Math.floor(
      (Date.UTC(year, month - 1, day) - Date.UTC(year, 0, 1)) / 86_400_000,
    ) % messages.length;

  return messages[index];
}

export async function wasMorningSent(day: string) {
  try {
    return (await readFile(sentPath, "utf8")).trim() === day;
  } catch {
    return false;
  }
}

export async function markMorningSent(day: string) {
  try {
    await mkdir(path.dirname(sentPath), { recursive: true });
    await writeFile(sentPath, day);
  } catch (error) {
    console.error("Failed to remember morning send:", error);
  }
}
